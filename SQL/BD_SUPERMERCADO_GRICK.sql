		CON_NOME AS "NOME DO CONSUMIDOR",
        CON_CPF  AS "CPF DO CONSUMIDOR"
FROM 	PRODUTO_CONSUMIDOR PC
INNER JOIN PRODUTO P ON (P.PRO_ID = PC.FK_PRO_ID)
INNER JOIN CONSUMIDOR C ON (C.CON_CPF = PC.FK_CON_CPF);

/* RETORNAR TODOS OS PRODUTOS E SEUS SUPERMERCADOS,
RETORNANDO TAMBÉM OS PRODUTOS SEM SUPERMERCADOS CADASTRADOS */
