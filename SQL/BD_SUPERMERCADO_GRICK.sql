		SUP_RAZAO_SOCIAL AS "SUPERMERCADO"
FROM PRODUTO P
LEFT JOIN SUPERMERCADO_PRODUTO SP ON (P.PRO_ID = SP.FK_PRO_ID)
LEFT JOIN SUPERMERCADO S ON (S.SUP_CNPJ = SP.FK_SUP_CNPJ);

