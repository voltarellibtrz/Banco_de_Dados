INNER JOIN CONSUMIDOR C ON (C.CON_CPF = PC.FK_CON_CPF);

/* 4- LISTE OS NOMES DOS PRODUTOS E OS RESPECTIVOS CONSUMIDORES QUE OS COMPRARAM */
