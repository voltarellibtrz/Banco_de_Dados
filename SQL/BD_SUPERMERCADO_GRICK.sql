		CON_NOME AS "CONSUMIDOR"
FROM 	PRODUTO P
LEFT JOIN PRODUTO_CONSUMIDOR PC ON (P.PRO_ID = PC.FK_PRO_ID)
LEFT JOIN CONSUMIDOR C ON (C.CON_CPF = PC.FK_CON_CPF);

